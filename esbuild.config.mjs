import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { copyFileSync, mkdirSync } from "node:fs";

/** Header prepended to the generated bundle. */
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

/** Whether this is a minified production build. */
const prod = process.argv[2] === "production";
/** Directory the bundle and static assets are written to. */
const OUT_DIR = "dist";

/** esbuild plugin that copies the manifest and styles into the output directory after each build. */
const copyStatics = {
  name: "copy-statics",
  setup(build) {
    build.onEnd(() => {
      mkdirSync(OUT_DIR, { recursive: true });
      for (const file of ["manifest.json", "styles.css"]) {
        copyFileSync(file, `${OUT_DIR}/${file}`);
      }
    });
  },
};

/** The esbuild build context bundling the plugin entry point. */
const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  plugins: [copyStatics],
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2021",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: `${OUT_DIR}/main.js`,
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
